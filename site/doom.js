/*
 * DOOM as a frame source, which is how the app already treats it: one contract,
 * two implementations. RecordedDoom replays captured attract-mode frames today
 * and a WasmDoom can take its place without touching this page.
 *
 * The frames are text captured from the real doom_ascii binary, so nothing GPL
 * is redistributed here. Only the characters it drew.
 */
import { measureCell } from "./renderer.js";
import { loadDoomSkeleton } from "./doom-play.js";

// Matches .open__doom's line-height in styles.css. Font-size is computed here
// rather than left to a fixed CSS clamp: the capture's column count is tied
// to record-doom.py's -scaling flag and travels in the payload, not hardcoded,
// so a size guess here could either underfill the box or, worse, overflow it
// — and with white-space:pre + overflow:hidden, overflow means the right or
// bottom of the frame gets silently clipped. That reads as "zoomed in" for a
// second, unrelated reason on top of the resolution one this was chasing.
const LINE_HEIGHT = 0.82;

/**
 * Largest font-size that fits `cols` columns by `rows` rows of monospace text
 * inside `el`'s content box without overflowing either axis.
 */
export function fitTextToBox(el, cols, rows) {
  const box = el.getBoundingClientRect();
  if (box.width <= 0 || box.height <= 0 || cols <= 0 || rows <= 0) return null;

  // Measured, not assumed: renderer.js's measureCell already exists for
  // exactly this (it drives the canvas grid's own cell sizing), so DOOM's
  // text grid is sized the same way rather than a second, divergent method.
  const canvas = document.createElement("canvas");
  const ctx = canvas.getContext("2d");
  ctx.font = `100px "IBM Plex Mono", monospace`;
  const advanceAt100 = measureCell(ctx, 100).w;

  // Width scales linearly with font-size via the measured advance. Height is
  // rows * fontPx * line-height directly — LINE_HEIGHT is *this* element's
  // own CSS line-height, unrelated to whatever ratio measureCell assumes for
  // its own caller, so it is not derived from measureCell's height at all.
  const byWidth = box.width / cols / (advanceAt100 / 100);
  const byHeight = box.height / (rows * LINE_HEIGHT);
  return Math.max(1, Math.min(byWidth, byHeight));
}

// The palette is generated by record-doom.py from its own f"#{r:02x}..."
// formatting, so it's well-formed by construction today. Validated anyway
// before landing in a style attribute: this function's only caller is a
// per-frame innerHTML assignment, and "trust the build output" is not a
// property worth relying on when a strict check costs one regex test.
const HEX_COLOR = /^#[0-9a-f]{6}$/i;
const MAX_RUN = 4096; // wider than any plausible captured row; guards against a corrupt count blowing up "█".repeat().

const HIGH_DENSITY = new Set(["@", "M", "W", "$", "%", "#", "0", "Q", "O", "X", "B", "R"]);
const MID_DENSITY = new Set(["+", "*", "=", "-", "i", "l", "t", "r", "f", "u", "v", "j", "z"]);

function escapeHtml(ch) {
  if (ch === "&") return "&amp;";
  if (ch === "<") return "&lt;";
  if (ch === ">") return "&gt;";
  return ch;
}

export function colorizeFrame(frameData, palette = []) {
  if (typeof frameData === "string") {
    if (frameData.includes("<span")) return frameData;
    let html = "";
    for (let i = 0; i < frameData.length; i++) {
      const ch = frameData[i];
      if (ch === "\n") html += "\n";
      else if (ch === " ") html += " ";
      else {
        const safe = escapeHtml(ch);
        if (HIGH_DENSITY.has(ch)) html += `<span class="d-hot">${safe}</span>`;
        else if (MID_DENSITY.has(ch)) html += `<span class="d-mid">${safe}</span>`;
        else html += `<span class="d-dim">${safe}</span>`;
      }
    }
    return html;
  }

  if (!Array.isArray(frameData)) return "";

  let html = "";
  for (let i = 0; i < frameData.length; i++) {
    const item = frameData[i];
    if (!Array.isArray(item)) continue;
    const [cIdx, count] = item;
    const safeCount = Number.isInteger(count) ? Math.max(0, Math.min(count, MAX_RUN)) : 0;
    if (cIdx === -1) {
      html += "\n";
    } else if (cIdx === -2) {
      // record-doom.py's NO_COLOR: doom_ascii drew this stretch as bare,
      // uncoloured space (a dark region), not a colour-less block glyph.
      // Rendering it as "█" would paint dark areas in the theme's default
      // text colour, inventing detail that was never actually drawn.
      html += " ".repeat(safeCount);
    } else {
      const blocks = "█".repeat(safeCount);
      const color = palette[cIdx];
      html += HEX_COLOR.test(color) ? `<span style="color:${color}">${blocks}</span>` : blocks;
    }
  }
  return html;
}

export class RecordedDoom {
  constructor(data) {
    this.frames = data.frames ?? [];
    this.palette = data.palette ?? [];
    this.fps = data.fps ?? 8;
    // Fallbacks match the pre-cols/rows capture format; anything recorded
    // after this change always carries its own real grid size.
    this.cols = data.cols ?? 160;
    this.rows = data.rows ?? 50;
    this.startedAt = 0;
    this.running = false;
  }

  start() {
    this.startedAt = performance.now();
    this.running = true;
  }

  stop() {
    this.running = false;
  }

  frame() {
    if (!this.running || this.frames.length === 0) return null;
    const elapsed = (performance.now() - this.startedAt) / 1000;
    const idx = Math.floor(elapsed * this.fps) % this.frames.length;
    return { frame: this.frames[idx], palette: this.palette };
  }
}

export async function mountDoom(preEl, buttonEl, stopButtonEl, { pauseAmbient, resumeAmbient } = {}) {
  let source = null;
  let attractRunning = true;
  let activeSession = null;

  const startAttract = () => {
    if (!source) return;
    attractRunning = true;
    let last = null;
    const draw = () => {
      if (!attractRunning) return;
      if (document.visibilityState === "visible") {
        const item = source.frame();
        if (item && item.frame !== last) {
          preEl.innerHTML = colorizeFrame(item.frame, item.palette);
          last = item.frame;
        }
      }
      requestAnimationFrame(draw);
    };
    requestAnimationFrame(draw);
  };

  try {
    const res = await fetch("assets/doom-attract.json");
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    source = new RecordedDoom(await res.json());
    source.start();
  } catch (err) {
    console.warn("DOOM recording unavailable", err);
  }

  if (source) {
    const applyFit = () => {
      const size = fitTextToBox(preEl, source.cols, source.rows);
      if (size) preEl.style.fontSize = `${size}px`;
    };
    applyFit();
    addEventListener("resize", applyFit);
    startAttract();
  }

  // innerHTML, not textContent: the "Live" state's message below embeds
  // <kbd> tags for the controls legend. Every caller passes a static
  // string literal from this file, never anything derived from user input.
  function status(html) {
    let el = document.getElementById("doomStatus");
    if (!el) {
      el = document.createElement("p");
      el.id = "doomStatus";
      el.className = "open__note";
      el.setAttribute("role", "status");
      buttonEl.closest(".open__acts").after(el);
    }
    el.innerHTML = html;
    return el;
  }

  function endSession() {
    activeSession?.stop();
    activeSession = null;
    stopButtonEl.hidden = true;
    resumeAmbient?.();
    buttonEl.disabled = false;
    buttonEl.textContent = "Play it";
    buttonEl.focus();
  }

  stopButtonEl.addEventListener("click", endSession);

  buttonEl.addEventListener(
    "click",
    async () => {
      attractRunning = false;
      buttonEl.disabled = true;
      buttonEl.textContent = "Loading…";
      // Nothing is preloaded yet, so this click fetches doom.wasm plus the
      // ~27MB WAD packaged alongside it — worth saying so, since a silent
      // 27MB fetch reads as a hang otherwise.
      status("Loading DOOM (about 27MB — this only happens once)…");

      const canvas = document.createElement("canvas");
      canvas.id = "doomPlayCanvas";
      canvas.className = "open__doom";
      canvas.style.display = "block";
      canvas.style.position = "relative";
      canvas.setAttribute("role", "application");
      canvas.setAttribute(
        "aria-label",
        "DOOM, playable. Arrow keys or WASD to move, Control to fire, Space to use, Enter to confirm menu selections, Escape for the in-game menu.",
      );
      preEl.replaceWith(canvas);

      try {
        pauseAmbient?.();
        // loadDoomSkeleton doesn't resolve until its own screen-melt
        // reveal (doom-play.js's meltReveal) has finished painting frame
        // by frame — by the time this line runs, gameplay is already
        // fully visible, so nothing here needs its own reveal animation.
        activeSession = await loadDoomSkeleton(canvas, { onSessionEnd: endSession });
        stopButtonEl.hidden = false;
        buttonEl.textContent = "Live";
        // Dim "note" styling is right for the pre-play caption but wrong
        // for this — it's the only visible controls legend a sighted
        // visitor gets, so it needs contrast, not decoration.
        status(
          `<kbd>↑</kbd><kbd>↓</kbd><kbd>←</kbd><kbd>→</kbd> or <kbd>WASD</kbd> move | <kbd>Ctrl</kbd> fire | <kbd>Space</kbd> use | <kbd>Esc</kbd> menu`,
        ).classList.add("doom-status--live");
      } catch (err) {
        console.warn("doom-wasm unavailable", err);
        resumeAmbient?.();
        buttonEl.disabled = false;
        buttonEl.textContent = "Play it";
        canvas.replaceWith(preEl);
        startAttract();
        status(
          "Couldn't load DOOM in this browser. Clone the repo and run ./scripts/setup.sh && swift run AsciiArcade instead.",
        );
      }
    },
    { once: true },
  );
}
